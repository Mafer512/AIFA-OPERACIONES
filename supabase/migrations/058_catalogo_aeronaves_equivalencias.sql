BEGIN;

CREATE TABLE IF NOT EXISTS public.catalogo_aeronaves_equivalencias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor_original text NOT NULL,
    -- Llave de búsqueda: mayúsculas, sin espacios sobrantes. "A320 " y "A320"
    -- comparten llave pero se conservan como filas distintas (trazabilidad).
    valor_clave text GENERATED ALWAYS AS
        (upper(btrim(regexp_replace(valor_original, '\s+', ' ', 'g')))) STORED,
    matricula text,
    codigo_iata text,
    codigo_icao text,
    nivel text NOT NULL,
    tipo_problema text NOT NULL,
    estado text NOT NULL,
    evidencia text NOT NULL,
    fuentes text,
    registros_muestra_jun2026 integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT catalogo_aeronaves_equiv_estado_ck
        CHECK (estado IN ('confirmado', 'pendiente')),
    CONSTRAINT catalogo_aeronaves_equiv_nivel_ck
        CHECK (nivel IN ('variante', 'tipo', 'ninguno')),
    -- Un confirmado de nivel 'variante' trae IATA; uno de nivel 'tipo', ICAO.
    CONSTRAINT catalogo_aeronaves_equiv_confirmado_ck
        CHECK (estado <> 'confirmado'
               OR (nivel = 'variante' AND codigo_iata IS NOT NULL)
               OR (nivel = 'tipo' AND codigo_icao IS NOT NULL AND codigo_iata IS NULL)
               OR (nivel = 'ninguno' AND codigo_iata IS NULL AND codigo_icao IS NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_catalogo_aeronaves_equiv_valor
    ON public.catalogo_aeronaves_equivalencias (valor_original, coalesce(matricula, ''));
CREATE INDEX IF NOT EXISTS idx_catalogo_aeronaves_equiv_clave
    ON public.catalogo_aeronaves_equivalencias (valor_clave);

COMMENT ON TABLE public.catalogo_aeronaves_equivalencias IS
    'Equivalencias de valores observados en "AERONAVE" de manifiestos hacia el catálogo '
    '(data/master/aircraft type.csv, IATA) y el ICAO Doc 8643. No modifica manifiestos. '
    'Sólo estado = confirmado debe usarse para traducir.';
COMMENT ON COLUMN public.catalogo_aeronaves_equivalencias.nivel IS
    'variante: código IATA exacto confirmado; tipo: sólo ICAO confirmado; ninguno: requiere revisar matrícula.';
COMMENT ON COLUMN public.catalogo_aeronaves_equivalencias.matricula IS
    'Si no es nulo, la equivalencia sólo aplica a esa matrícula (sin guiones ni espacios).';
COMMENT ON COLUMN public.catalogo_aeronaves_equivalencias.registros_muestra_jun2026 IS
    'Manifiestos con ese valor en la muestra de junio 2026 (supabase/migrations/jun2026_parts).';

-- Mismo patrón que los catálogos de Conciliación (008).
DROP TRIGGER IF EXISTS catalogo_aeronaves_equivalencias_updated_at
    ON public.catalogo_aeronaves_equivalencias;
CREATE TRIGGER catalogo_aeronaves_equivalencias_updated_at
    BEFORE UPDATE ON public.catalogo_aeronaves_equivalencias
    FOR EACH ROW EXECUTE FUNCTION public.conci_catalogos_set_updated_at();

ALTER TABLE public.catalogo_aeronaves_equivalencias ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS catalogo_aeronaves_equiv_read ON public.catalogo_aeronaves_equivalencias;
CREATE POLICY catalogo_aeronaves_equiv_read
    ON public.catalogo_aeronaves_equivalencias
    FOR SELECT TO authenticated
    USING (true);

DROP POLICY IF EXISTS catalogo_aeronaves_equiv_write ON public.catalogo_aeronaves_equivalencias;
CREATE POLICY catalogo_aeronaves_equiv_write
    ON public.catalogo_aeronaves_equivalencias
    FOR ALL TO authenticated
    USING (public.conci_catalogos_can_edit())
    WITH CHECK (public.conci_catalogos_can_edit());

GRANT SELECT ON TABLE public.catalogo_aeronaves_equivalencias TO authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.catalogo_aeronaves_equivalencias TO authenticated;
GRANT ALL ON TABLE public.catalogo_aeronaves_equivalencias TO service_role;

