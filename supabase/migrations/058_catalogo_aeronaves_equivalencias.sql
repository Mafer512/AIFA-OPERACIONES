-- 1) 33 filas: 16 confirmadas y 17 pendientes.
SELECT 'equivalencias por estado' AS reporte, estado, nivel, count(*) AS filas,
       sum(registros_muestra_jun2026) AS manifiestos_muestra
  FROM public.catalogo_aeronaves_equivalencias
 GROUP BY estado, nivel
 ORDER BY estado, nivel;

-- 2) La muestra de junio suma 4,589 manifiestos (31 valores observados).
SELECT 'muestra junio 2026' AS reporte, sum(registros_muestra_jun2026) AS manifiestos
  FROM public.catalogo_aeronaves_equivalencias;

-- 3) Ninguna clave normalizada tiene dos destinos confirmados distintos.
SELECT 'claves con destinos en conflicto (debe salir vacío)' AS reporte, valor_clave, matricula
  FROM public.catalogo_aeronaves_equivalencias
 WHERE estado = 'confirmado'
 GROUP BY valor_clave, matricula
HAVING count(DISTINCT (coalesce(codigo_iata, ''), coalesce(codigo_icao, ''))) > 1;

