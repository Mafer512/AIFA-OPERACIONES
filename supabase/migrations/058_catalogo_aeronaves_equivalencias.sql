-- 058 · Catálogo de aeronaves: tabla de equivalencias de AERONAVE
--
-- SÍNTOMA
--   La columna "AERONAVE" de los manifiestos mezcla tres cosas: códigos IATA
--   del itinerario (32N, 7M8), códigos ICAO tecleados (B738) y texto libre de
--   los Excel y del portal ("A-320", "A320 ", "B737-8MAX", "E-195", "C208B").
--   Muestra de junio 2026 (4,589 manifiestos): 31 escrituras distintas, ninguna
--   es un código IATA del catálogo.
--
-- CAUSA
--   El catálogo de modelos (data/master/aircraft type.csv) sólo traduce
--   códigos; el texto libre entra tal cual por la importación de Excel y por el
--   campo EQUIPO del portal, y nada registra a qué modelo corresponde.
--
-- QUÉ HACE
--   Crea public.catalogo_aeronaves_equivalencias: cada valor original
--   observado, el código canónico (IATA del catálogo / ICAO Doc 8643) cuando
--   hay evidencia, el estado (confirmado / pendiente), la evidencia y la
--   cantidad de registros en la muestra de junio 2026.
--     · NO modifica ningún manifiesto: el valor original se queda donde está.
--       La equivalencia sólo se usa al consultar (ver
--       scripts/diagnostico-catalogo-aeronaves.sql).
--     · Sólo las filas con estado = 'confirmado' deben usarse para traducir.
--       En las 'pendiente', codigo_iata/codigo_icao son PROPUESTAS sin validar.
--     · nivel: 'variante' = se sabe el código IATA exacto; 'tipo' = sólo se
--       sabe el ICAO (p. ej. A320-233 es A320ceo, pero no si es 320 o 32A);
--       'ninguno' = no se puede asignar sin revisar la matrícula.
--     · matricula: cuando la equivalencia sólo vale para una aeronave
--       (p. ej. "A340-800" en YV3535).
--   Fuentes: ICAO Doc 8643 (doc8643.icao.int, consultado 2026-10-06), FAA
--   Aircraft Registry (registry.faa.gov, 2026-10-06), EASA TCDS A.064.
--   Detalle y casos pendientes: docs/catalogo-aeronaves-revision.md
--
-- REQUIERE
--   008 (conci_catalogos_can_edit y conci_catalogos_set_updated_at).
--   No se pudo ejecutar contra una base al prepararla: correrla primero con
--   el ROLLBACK final, tal como indica el modo de uso.
--
-- MODO DE USO (igual que 036)
--   1) Correr el archivo completo tal cual. Termina en ROLLBACK: no persiste
