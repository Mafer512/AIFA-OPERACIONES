-- Cambio de estado: sólo por aquí (no hay política UPDATE sobre la tabla), así
-- los tiempos de atención y resolución los calcula la base, no la página.
CREATE OR REPLACE FUNCTION public.calidad_actualizar_estado(
  p_folio   text,
  p_estado  text,
  p_nota    text,
  p_usuario text DEFAULT NULL
)
RETURNS public.calidad_incidencias
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  _inc   public.calidad_incidencias;
  _ahora timestamptz := now();
  _nota  text := left(btrim(coalesce(p_nota, '')), 300);
  _email text := nullif(lower(coalesce(auth.jwt() ->> 'email', '')), '');
  _quien text;
BEGIN
  IF NOT public.calidad_puede_editar() THEN
    RAISE EXCEPTION 'Tu cuenta no puede actualizar incidencias de Calidad.' USING ERRCODE = '42501';
  END IF;
  IF p_estado IS NULL OR p_estado NOT IN ('Pendiente', 'En proceso', 'Solucionada') THEN
    RAISE EXCEPTION 'Estado inválido.' USING ERRCODE = '22023';
  END IF;
  IF length(_nota) < 5 THEN
    RAISE EXCEPTION 'Escribe una nota de al menos 5 caracteres.' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO _inc FROM public.calidad_incidencias WHERE folio = p_folio FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No se encontró la incidencia %.', p_folio USING ERRCODE = 'P0002';
  END IF;
  IF _inc.estado = p_estado THEN
    RAISE EXCEPTION 'La incidencia ya está en «%».', p_estado USING ERRCODE = '22023';
  END IF;
  IF _inc.estado = 'Solucionada' AND NOT public.calidad_es_admin() THEN
    RAISE EXCEPTION 'La incidencia está cerrada; sólo un administrador de Calidad puede reabrirla.' USING ERRCODE = '42501';
  END IF;

  _quien := coalesce(nullif(btrim(coalesce(p_usuario, '')), ''), _email, 'Usuario');

  UPDATE public.calidad_incidencias SET
    estado            = p_estado,
    tiempo_atencion   = CASE WHEN p_estado <> 'Pendiente' AND tiempo_atencion IS NULL
                             THEN greatest(1, round(extract(epoch FROM (_ahora - fecha)) / 60))::integer
                             ELSE tiempo_atencion END,
    tiempo_resolucion = CASE WHEN p_estado = 'Solucionada'
                             THEN round((extract(epoch FROM (_ahora - fecha)) / 3600)::numeric, 2)
                             ELSE NULL END,
    observaciones     = _nota,
    actualizado_en    = _ahora
  WHERE id = _inc.id
  RETURNING * INTO _inc;

  INSERT INTO public.calidad_incidencia_seguimiento (incidencia_id, fecha, estado, nota, usuario, usuario_email)
  VALUES (_inc.id, _ahora, p_estado, _nota, left(_quien, 200), _email);

  RETURN _inc;
END;
$$;

REVOKE ALL ON FUNCTION public.calidad_actualizar_estado(text, text, text, text) FROM public;
GRANT EXECUTE ON FUNCTION public.calidad_actualizar_estado(text, text, text, text) TO authenticated;

