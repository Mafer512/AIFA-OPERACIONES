-- Consecutivo por año para el folio. Sólo lo toca el trigger.
CREATE TABLE IF NOT EXISTS public.calidad_folios (
  anio    integer PRIMARY KEY,
  ultimo  integer NOT NULL DEFAULT 0
);

-- Alta: folio, estado inicial, quién la registró (del token, no de la página)
-- y fecha que no puede ser futura.
CREATE OR REPLACE FUNCTION public._calidad_incidencia_alta()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  _anio integer;
  _n    integer;
BEGIN
  NEW.fecha := coalesce(NEW.fecha, now());
  IF NEW.fecha > now() + interval '5 minutes' THEN
    RAISE EXCEPTION 'La fecha de la incidencia no puede ser futura.' USING ERRCODE = '22007';
  END IF;

  _anio := extract(year FROM NEW.fecha AT TIME ZONE 'America/Mexico_City')::integer;
  INSERT INTO public.calidad_folios AS f (anio, ultimo) VALUES (_anio, 1)
  ON CONFLICT (anio) DO UPDATE SET ultimo = f.ultimo + 1
  RETURNING ultimo INTO _n;

  NEW.folio                := 'INC-' || _anio || '-' || lpad(_n::text, 4, '0');
  NEW.vuelo                := upper(btrim(NEW.vuelo));
  NEW.equipo               := nullif(btrim(coalesce(NEW.equipo, '')), '');
  NEW.descripcion          := btrim(NEW.descripcion);
  NEW.estado               := 'Pendiente';
  NEW.tiempo_atencion      := NULL;
  NEW.tiempo_resolucion    := NULL;
  NEW.observaciones        := 'En espera de asignación.';
  NEW.registrado_por_email := nullif(lower(coalesce(auth.jwt() ->> 'email', '')), '');
  NEW.registrado_por       := coalesce(nullif(btrim(coalesce(NEW.registrado_por, '')), ''), NEW.registrado_por_email, 'Usuario');
  NEW.creado_en            := now();
  NEW.actualizado_en       := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_calidad_incidencia_alta ON public.calidad_incidencias;
CREATE TRIGGER trg_calidad_incidencia_alta
BEFORE INSERT ON public.calidad_incidencias
FOR EACH ROW EXECUTE FUNCTION public._calidad_incidencia_alta();

