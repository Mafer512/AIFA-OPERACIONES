-- ============================================================================
-- CALIDAD · SIGEC (Edificio Terminal)
-- Incidencias de equipaje, encuestas a pasajeros y aerolíneas, documentación
-- controlada y directorio. La página vive en calidad/ y se abre desde
-- Edificio Terminal → Calidad (SIGEC).
--
-- Quién entra y qué puede hacer sale de lo que ya existe en AIFA Operaciones:
-- Administración de usuarios → módulo «Calidad (SIGEC)» (clave 'calidad').
--
--   admin / superadmin          → admin       todo, y ve la lista de usuarios
--   nivel 'edit' en el módulo   → supervisor  cambia estados, publica documentos, directorio
--   nivel 'capture'             → capturista  registra incidencias y encuestas
--   nivel 'read'                → consulta    sólo consulta y exporta
--   sin el módulo en su lista   → sin acceso
--
-- La regla vive aquí (RLS), no sólo en la página: aunque alguien cambie su rol
-- en el navegador, la base no le deja leer ni escribir lo que no le toca.
--
-- Evidencias (JPG, PNG, WEBP) y documentos (PDF, DOCX, XLSX, PPTX) van a
-- buckets PRIVADOS y se abren con enlaces firmados que vencen.
--
-- Requiere db/rbac_roles_v2.sql (public.user_section_level), que ya está corrido.
-- Es idempotente: se puede correr de nuevo. No toca tablas de otros módulos.
-- Supabase → SQL Editor → pegar → Run.
-- ============================================================================

BEGIN;

-- ── 1. Rol dentro de Calidad ────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.calidad_mi_rol()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT CASE public.user_section_level('calidad')
    WHEN 'admin'   THEN 'admin'
    WHEN 'edit'    THEN 'supervisor'
    WHEN 'capture' THEN 'capturista'
    WHEN 'read'    THEN 'consulta'
    ELSE NULL
  END;
$$;

CREATE OR REPLACE FUNCTION public.calidad_puede_ver()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT public.calidad_mi_rol() IS NOT NULL; $$;

CREATE OR REPLACE FUNCTION public.calidad_puede_capturar()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT coalesce(public.calidad_mi_rol() IN ('admin', 'supervisor', 'capturista'), false); $$;

CREATE OR REPLACE FUNCTION public.calidad_puede_editar()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT coalesce(public.calidad_mi_rol() IN ('admin', 'supervisor'), false); $$;

CREATE OR REPLACE FUNCTION public.calidad_es_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT coalesce(public.calidad_mi_rol() = 'admin', false); $$;

REVOKE ALL ON FUNCTION public.calidad_mi_rol()         FROM public;
REVOKE ALL ON FUNCTION public.calidad_puede_ver()      FROM public;
REVOKE ALL ON FUNCTION public.calidad_puede_capturar() FROM public;
REVOKE ALL ON FUNCTION public.calidad_puede_editar()   FROM public;
REVOKE ALL ON FUNCTION public.calidad_es_admin()       FROM public;
GRANT EXECUTE ON FUNCTION public.calidad_mi_rol()         TO authenticated;
GRANT EXECUTE ON FUNCTION public.calidad_puede_ver()      TO authenticated;
GRANT EXECUTE ON FUNCTION public.calidad_puede_capturar() TO authenticated;
GRANT EXECUTE ON FUNCTION public.calidad_puede_editar()   TO authenticated;
GRANT EXECUTE ON FUNCTION public.calidad_es_admin()       TO authenticated;

-- ── 2. Incidencias ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.calidad_incidencias (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio                 text,                       -- INC-AAAA-NNNN, lo pone la base
  fecha                 timestamptz NOT NULL DEFAULT now(),
  tipo                  text NOT NULL,
  aerolinea             text NOT NULL,              -- código OACI: AMX, VIV, VOI…
  vuelo                 text NOT NULL,
  nivel                 text NOT NULL,
  edificio              text NOT NULL DEFAULT 'T1',
  equipo                text,
  severidad             text NOT NULL,
  estado                text NOT NULL DEFAULT 'Pendiente',
  descripcion           text NOT NULL,
  observaciones         text,
  tiempo_atencion       integer,                    -- minutos hasta la primera atención
  tiempo_resolucion     numeric(10,2),              -- horas hasta quedar solucionada
  registrado_por        text,
  registrado_por_email  text,
  evidencia_path        text,                       -- incidencias/<uuid>.<jpg|png|webp>
  creado_en             timestamptz NOT NULL DEFAULT now(),
  actualizado_en        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT calidad_inc_tipo_chk       CHECK (length(btrim(tipo)) BETWEEN 1 AND 60),
  CONSTRAINT calidad_inc_aerolinea_chk  CHECK (aerolinea ~ '^[A-Z0-9]{2,3}$'),
  CONSTRAINT calidad_inc_vuelo_chk      CHECK (vuelo ~ '^[A-Z0-9]{2,3}[0-9]{1,4}[A-Z]?$'),
  CONSTRAINT calidad_inc_nivel_chk      CHECK (nivel IN ('PB', 'N1', 'N2', 'N3')),
  CONSTRAINT calidad_inc_edificio_chk   CHECK (length(btrim(edificio)) BETWEEN 1 AND 20),
  CONSTRAINT calidad_inc_equipo_chk     CHECK (equipo IS NULL OR equipo ~ '^[A-Za-z0-9 _./-]{1,30}$'),
  CONSTRAINT calidad_inc_severidad_chk  CHECK (severidad IN ('Baja', 'Media', 'Alta', 'Crítica')),
  CONSTRAINT calidad_inc_estado_chk     CHECK (estado IN ('Pendiente', 'En proceso', 'Solucionada')),
  CONSTRAINT calidad_inc_desc_chk       CHECK (length(btrim(descripcion)) BETWEEN 10 AND 500),
  CONSTRAINT calidad_inc_obs_chk        CHECK (observaciones IS NULL OR length(observaciones) <= 300),
  CONSTRAINT calidad_inc_tiempos_chk    CHECK (coalesce(tiempo_atencion, 0) >= 0 AND coalesce(tiempo_resolucion, 0) >= 0),
  CONSTRAINT calidad_inc_registro_chk   CHECK (registrado_por IS NULL OR length(registrado_por) <= 200),
  CONSTRAINT calidad_inc_evidencia_chk  CHECK (evidencia_path IS NULL OR evidencia_path ~ '^incidencias/[0-9a-f-]{36}\.(jpg|png|webp)$')
);

