-- ── 6. Usuarios con acceso (Configuración → Usuarios y roles) ───────────────
-- Mismo cálculo que user_section_level('calidad'), pero para cada cuenta.
-- Sólo responde a un administrador de Calidad.
CREATE OR REPLACE FUNCTION public.calidad_usuarios()
RETURNS TABLE (id text, nombre text, usuario text, area text, rol text, activo boolean, ultimo_acceso timestamptz)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, auth
AS $$
  WITH cuentas AS (
    SELECT u.id, lower(u.email) AS email, u.last_sign_in_at,
           coalesce(nullif(btrim(p.full_name), ''),
                    nullif(btrim(u.raw_user_meta_data ->> 'full_name'), ''),
                    nullif(btrim(u.raw_user_meta_data ->> 'name'), ''),
                    lower(u.email)) AS nombre,
           r.role, coalesce(r.permissions, '{}'::jsonb) AS perms,
           EXISTS (SELECT 1 FROM public.usuarios_aplicaciones ua
                   JOIN public.aplicaciones a ON a.id = ua.aplicacion_id
                   WHERE ua.usuario_id = u.id AND a.clave = 'OPERACIONES' AND ua.estado = 'ACTIVO') AS activa_ops
    FROM auth.users u
    JOIN public.user_roles r ON r.user_id = u.id
    LEFT JOIN public.profiles p ON p.id = u.id
    WHERE public.calidad_es_admin() AND u.email IS NOT NULL
  ),
  niveles AS (
    SELECT c.*,
      CASE
        WHEN c.role IN ('admin', 'superadmin') THEN 'admin'
        WHEN jsonb_typeof(c.perms -> 'allowed_sections') = 'array'
             AND jsonb_array_length(c.perms -> 'allowed_sections') > 0
             AND NOT ((c.perms -> 'allowed_sections') ? 'calidad') THEN NULL
        WHEN (c.perms #>> '{section_levels,calidad}') = 'edit'    THEN 'supervisor'
        WHEN (c.perms #>> '{section_levels,calidad}') = 'capture' THEN 'capturista'
        WHEN (c.perms #>> '{section_levels,calidad}') = 'read'    THEN 'consulta'
        WHEN c.role IN ('editor', 'colab_editor', 'control_fauna', 'servicio_medico') THEN 'supervisor'
        WHEN c.role = 'capturista' THEN 'capturista'
        ELSE 'consulta'
      END AS rol_calidad
    FROM cuentas c
  )
  SELECT n.id::text, n.nombre::text, n.email::text,
         coalesce(nullif(btrim(n.perms ->> 'area'), ''), '')::text,
         n.rol_calidad::text,
         (n.activa_ops OR n.role IN ('admin', 'superadmin')) AS activo,
         n.last_sign_in_at
  FROM niveles n
  WHERE n.rol_calidad IS NOT NULL
  ORDER BY CASE n.rol_calidad WHEN 'admin' THEN 1 WHEN 'supervisor' THEN 2 WHEN 'capturista' THEN 3 ELSE 4 END, n.nombre;
$$;

REVOKE ALL ON FUNCTION public.calidad_usuarios() FROM public;
