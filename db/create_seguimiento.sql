COMMENT ON TABLE public.seguimiento_tareas IS
  'Seguimiento de la Dirección de Operación: órdenes, renovaciones, certificados y pendientes por subdirección.';

CREATE OR REPLACE FUNCTION public._touch_seguimiento()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.actualizado_en := now();
  -- La fecha de cierre la pone la base: así no depende del reloj de cada equipo.
  IF NEW.estatus = 'completada' AND (TG_OP = 'INSERT' OR OLD.estatus IS DISTINCT FROM 'completada') THEN
    NEW.completada_en := coalesce(NEW.completada_en, now());
  ELSIF NEW.estatus <> 'completada' THEN
    NEW.completada_en := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_touch_seguimiento ON public.seguimiento_tareas;
CREATE TRIGGER trg_touch_seguimiento
BEFORE INSERT OR UPDATE ON public.seguimiento_tareas
FOR EACH ROW EXECUTE FUNCTION public._touch_seguimiento();

-- ── 3. Comentarios y bitácora ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.seguimiento_comentarios (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tarea_id     uuid NOT NULL REFERENCES public.seguimiento_tareas(id) ON DELETE CASCADE,
  autor        text,
  autor_email  text DEFAULT lower(auth.jwt() ->> 'email'),
  texto        text NOT NULL,
  creado_en    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT seguimiento_comentarios_texto_chk CHECK (length(btrim(texto)) BETWEEN 1 AND 4000)
);
CREATE INDEX IF NOT EXISTS idx_seguimiento_comentarios_tarea ON public.seguimiento_comentarios (tarea_id, creado_en);

CREATE TABLE IF NOT EXISTS public.seguimiento_actividad (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarea_id     uuid NOT NULL REFERENCES public.seguimiento_tareas(id) ON DELETE CASCADE,
  autor        text,
  autor_email  text DEFAULT lower(auth.jwt() ->> 'email'),
  accion       text NOT NULL,
  detalle      jsonb NOT NULL DEFAULT '{}'::jsonb,
  creado_en    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_seguimiento_actividad_tarea ON public.seguimiento_actividad (tarea_id, creado_en DESC);

