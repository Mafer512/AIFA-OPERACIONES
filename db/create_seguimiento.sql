-- ============================================================================
-- SEGUIMIENTO · Dirección de Operación
-- Órdenes, renovaciones, certificados y pendientes, por subdirección.
--
-- Módulo de acceso restringido: sólo entran las cuentas registradas en
-- public.seguimiento_acceso. La regla vive aquí, en la base (RLS), y no sólo en
-- la página: aunque alguien abra #seguimiento, sin estar en la lista no lee ni
-- escribe nada.
--
--   admin  → todo, y además administra quién entra
--   editor → crea, edita y comenta
--   lector → consulta y comenta
--
-- Las evidencias (PDF, JPG, PNG) van a un bucket PRIVADO y se abren con
-- enlaces firmados que vencen.
--
-- Es idempotente: se puede correr de nuevo. No toca tablas de otros módulos.
-- Supabase → SQL Editor → pegar → Run.
-- ============================================================================

BEGIN;

-- ── 1. Quién entra ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.seguimiento_acceso (
  email         text PRIMARY KEY,                 -- siempre en minúsculas
  nombre        text,
  rol           text NOT NULL DEFAULT 'editor',
  agregado_por  text,
  creado_en     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT seguimiento_acceso_rol_chk CHECK (rol IN ('admin', 'editor', 'lector')),
  CONSTRAINT seguimiento_acceso_email_chk CHECK (email = lower(btrim(email)) AND email LIKE '%@%')
);

COMMENT ON TABLE public.seguimiento_acceso IS
  'Cuentas que pueden entrar al módulo Seguimiento y con qué rol.';

-- El rol de quien está conectado, o NULL si no tiene acceso. SECURITY DEFINER
-- para que las políticas puedan consultarla sin abrir la tabla a todos.
CREATE OR REPLACE FUNCTION public.seguimiento_mi_rol()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT a.rol
  FROM public.seguimiento_acceso a
  WHERE a.email = lower(coalesce(auth.jwt() ->> 'email', ''))
  LIMIT 1;
$$;

REVOKE ALL ON FUNCTION public.seguimiento_mi_rol() FROM public;
GRANT EXECUTE ON FUNCTION public.seguimiento_mi_rol() TO authenticated;

CREATE OR REPLACE FUNCTION public.seguimiento_puede_ver()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT public.seguimiento_mi_rol() IS NOT NULL; $$;

CREATE OR REPLACE FUNCTION public.seguimiento_puede_editar()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT coalesce(public.seguimiento_mi_rol() IN ('admin', 'editor'), false); $$;

CREATE OR REPLACE FUNCTION public.seguimiento_es_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT coalesce(public.seguimiento_mi_rol() = 'admin', false); $$;

REVOKE ALL ON FUNCTION public.seguimiento_puede_ver() FROM public;
REVOKE ALL ON FUNCTION public.seguimiento_puede_editar() FROM public;
REVOKE ALL ON FUNCTION public.seguimiento_es_admin() FROM public;
GRANT EXECUTE ON FUNCTION public.seguimiento_puede_ver() TO authenticated;
GRANT EXECUTE ON FUNCTION public.seguimiento_puede_editar() TO authenticated;
GRANT EXECUTE ON FUNCTION public.seguimiento_es_admin() TO authenticated;

-- ── 2. Tareas ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.seguimiento_tareas (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  folio                bigint GENERATED BY DEFAULT AS IDENTITY,
  titulo               text NOT NULL,
  descripcion          text,
  tipo                 text NOT NULL DEFAULT 'orden',
  subdireccion         text NOT NULL,
  gerencia             text,
  estatus              text NOT NULL DEFAULT 'pendiente',
  prioridad            text NOT NULL DEFAULT 'normal',
  responsable          text,
  responsable_num      text,           -- No. Empleado en agenda_2026, si se eligió del directorio
  responsable_tel      text,           -- para el recordatorio por WhatsApp
  fecha_inicio         date,
  fecha_limite         date,
  completada_en        timestamptz,
  recurrencia          text NOT NULL DEFAULT 'ninguna',
  recurrencia_meses    integer,        -- sólo con recurrencia 'personalizada': cada cuántos meses (18, 36…)
  aviso_dias           integer NOT NULL DEFAULT 7,
  referencia           text,           -- oficio, minuta o documento que la origina
  etiquetas            text[] NOT NULL DEFAULT '{}',
  checklist            jsonb NOT NULL DEFAULT '[]'::jsonb,   -- [{id, texto, hecho}]
  evidencias           jsonb NOT NULL DEFAULT '[]'::jsonb,   -- [{path, nombre, tipo, tam, subido_por, subido_en}]
  tarea_origen         uuid,           -- primera de la cadena, en las recurrentes
  siguiente_id         uuid,           -- la ocurrencia que se programó al completarla
  ultimo_recordatorio  timestamptz,
  creado_por           text,
  creado_por_email     text,
  actualizado_por      text,
  creado_en            timestamptz NOT NULL DEFAULT now(),
  actualizado_en       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT seguimiento_tareas_titulo_chk     CHECK (length(btrim(titulo)) BETWEEN 1 AND 300),
  CONSTRAINT seguimiento_tareas_tipo_chk       CHECK (tipo IN ('orden', 'renovacion', 'certificado', 'compromiso', 'tarea')),
  CONSTRAINT seguimiento_tareas_subdir_chk     CHECK (subdireccion IN ('DO', 'SSO', 'SSA', 'SSC', 'SI', 'SGE')),
  CONSTRAINT seguimiento_tareas_estatus_chk    CHECK (estatus IN ('pendiente', 'en_proceso', 'en_revision', 'detenida', 'completada', 'cancelada')),
  CONSTRAINT seguimiento_tareas_prioridad_chk  CHECK (prioridad IN ('urgente', 'alta', 'normal', 'baja')),
  CONSTRAINT seguimiento_tareas_recurr_chk     CHECK (recurrencia IN ('ninguna', 'mensual', 'bimestral', 'trimestral', 'semestral', 'anual', 'bienal', 'personalizada')),
  CONSTRAINT seguimiento_tareas_recurr_meses_chk CHECK (recurrencia <> 'personalizada' OR recurrencia_meses BETWEEN 1 AND 240),
  CONSTRAINT seguimiento_tareas_aviso_chk      CHECK (aviso_dias BETWEEN 0 AND 365),
  CONSTRAINT seguimiento_tareas_fechas_chk     CHECK (fecha_inicio IS NULL OR fecha_limite IS NULL OR fecha_limite >= fecha_inicio),
  CONSTRAINT seguimiento_tareas_checklist_chk  CHECK (jsonb_typeof(checklist) = 'array'),
  CONSTRAINT seguimiento_tareas_evidencias_chk CHECK (jsonb_typeof(evidencias) = 'array')
);

